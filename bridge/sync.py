OPENCODE_PLUGIN = """// agents-bridge: generated - guard hooks for OpenCode (adapter -> hooks from the source config)
const ADAPTER = ["/usr/bin/python3", "-I", "__ADAPTER__", "--harness", "opencode", "--dispatch", "--event"];
const SECRET_ENV = __SECRETS__;

async function run(event, payload) {
  const p = Bun.spawn([...ADAPTER, event], { stdin: "pipe", stdout: "pipe", stderr: "pipe" });
  p.stdin.write(JSON.stringify(payload)); p.stdin.end();
  const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
  return { out, err, code };
}

export const AgentsBridgeGuard = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    const r = await run("PreToolUse", { cwd: directory, session_id: input.sessionID, tool_name: input.tool, tool_input: output.args });
    if (r.code !== 0) throw new Error(r.err.trim() || "BLOCKED by agents-bridge guard (code " + r.code + ")");
  },
  "tool.execute.after": async (input) => {
    await run("PostToolUse", { cwd: directory, session_id: input.sessionID, tool_name: input.tool, tool_input: input.args });
  },
  // MCP header secrets live only in the OpenCode process, never in the agent's shell
  "shell.env": async (_input, output) => { for (const k of SECRET_ENV) output.env[k] = ""; },
});
"""


def opencode_mcp(servers: dict[str, dict]) -> dict:
    out = {}
    for n, s in servers.items():
        if s["kind"] == "http":
            c = {"type": "remote", "url": s["url"], "enabled": True}
            hdr = CFG["mcp_secret_headers"].get(n)
            if hdr:
                c["headers"] = {h: re.sub(r"\$\{?([A-Z0-9_]+)\}?", r"{env:\1}", v) if "$" in v else "{env:" + v + "}"
                                for h, v in hdr.items()}
        else:
            env = dict(s["env"])
            env.update({k: "{env:" + v + "}" for k, v in s["env_vars"]})
            c = {"type": "local", "command": [s["command"], *s["args"]], "enabled": True, **({"environment": env} if env else {})}
        out[n] = c
    return out


