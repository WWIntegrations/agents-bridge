def git_exclude(repo: Path, patterns: list[str]) -> None:
    if not CFG["project_files_exclude"] or not (repo / ".git").is_dir():
        return
    ex = repo / ".git" / "info" / "exclude"
    cur = ex.read_text() if ex.is_file() else ""
    add = [p for p in patterns if p not in cur.splitlines()]
    if add and not DRY:
        ex.parent.mkdir(parents=True, exist_ok=True)
        ex.write_text(cur + ("" if cur.endswith("\n") or not cur else "\n") + "# agents-bridge\n" + "\n".join(add) + "\n")
    if add:
        note(f"exclude {repo}: {' '.join(add)}")


# ================================================================================================ TOML
def _tk(k: str) -> str:
    return k if re.fullmatch(r"[A-Za-z0-9_-]+", k) else json.dumps(k, ensure_ascii=False)


def _tv(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(_tv(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{_tk(k)} = {_tv(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


def toml_dump(d: dict, prefix: str = "") -> str:
    sc = [(k, v) for k, v in d.items() if not isinstance(v, dict)]
    tb = [(k, v) for k, v in d.items() if isinstance(v, dict)]
    out = []
    if prefix and (sc or not tb):
        out.append(f"[{prefix}]")
    out += [f"{_tk(k)} = {_tv(v)}" for k, v in sc]
    for k, v in tb:
        if out:
            out.append("")
        out.append(toml_dump(v, f"{prefix}.{_tk(k)}" if prefix else _tk(k)))
    return "\n".join(out)


def merge_managed_toml(path: Path, gen: dict) -> str:
    """Our keys live between markers at the top; everything else (Codex's own writes) is preserved and wins."""
    cur = path.read_text() if path.is_file() else ""
    if MARK_BEG in cur and MARK_END in cur:
        pre, rest = cur.split(MARK_BEG, 1)
        inside, post = rest.split(MARK_END, 1)
        outside = pre + post
        ours = set(re.findall(r"^\[([^\]]+)\]\s*$", toml_dump(gen), re.M))
        ours_top = {k for k, v in gen.items() if not isinstance(v, dict)}
        moved_top, moved_tabs, sec, lines = [], [], None, []

        def flush():
            if sec is not None and sec not in ours and lines:
                moved_tabs.extend(["", f"[{sec}]", *lines])

        for ln in inside.splitlines():  # rescue what Codex wrote inside our block (e.g. [hooks.state.*])
            m = re.match(r"^\[([^\]]+)\]\s*$", ln)
            if m:
                flush()
                sec, lines = m.group(1), []
            elif sec is None:
                k = re.match(r"^([A-Za-z0-9_-]+)\s*=", ln)
                if k and k.group(1) not in ours_top:
                    moved_top.append(ln)
            elif ln.strip():
                lines.append(ln)
        flush()
        outside = "\n".join(moved_top) + "\n" + outside.strip() + "\n" + "\n".join(moved_tabs) + "\n"
    else:
        outside = cur
    try:
        user = tomllib.loads(outside)
    except tomllib.TOMLDecodeError:
        user = {}

    def strip(g: dict, u: dict) -> dict:
        out = {}
        for k, v in g.items():
            if k in u and not (isinstance(v, dict) and isinstance(u[k], dict)):
                continue
            if isinstance(v, dict) and isinstance(u.get(k), dict):
                sub = strip(v, u[k])
                if sub:
                    out[k] = sub
            else:
                out[k] = v
        return out

    g = strip(gen, user)
    scal = {k: v for k, v in g.items() if not isinstance(v, dict)}
    tabs = {k: v for k, v in g.items() if isinstance(v, dict)}
    ls = outside.strip("\n").splitlines()
    first = next((i for i, ln in enumerate(ls) if re.match(r"^\s*\[", ln)), len(ls))
    u_top = "\n".join(ln for ln in ls[:first] if ln.strip()).strip()
    u_tabs = "\n".join(ls[first:]).strip()
    text = (u_top + "\n\n" if u_top else "") + MARK_BEG + "\n" + toml_dump(scal) + "\n\n" + toml_dump(tabs) + "\n" \
        + MARK_END + "\n" + ("\n" + u_tabs + "\n" if u_tabs else "")
    parsed = tomllib.loads(text)
    for k, v in user.items():
        if not isinstance(v, dict):
            assert parsed.get(k) == v, f"merge changed key {k}"
    return text


def json_merge(path: Path, managed: dict) -> str:
    try:
        cur = json.loads(path.read_text()) if path.is_file() else {}
    except ValueError:
        cur = {}
    for k, v in managed.items():
        cur[k] = {**cur[k], **v} if isinstance(v, dict) and isinstance(cur.get(k), dict) else v
    return json.dumps(cur, indent=2, ensure_ascii=False) + "\n"


