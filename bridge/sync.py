"""agents-bridge sync: author your agent setup ONCE (in Claude Code or in Codex), get it in every other agent.

Source of truth stays where you already work ("source": "claude" | "codex" in bridge.json):

                 claude source                          codex source
  instructions   ~/.agents/AGENTS.md (or CLAUDE.md)     ~/.codex/AGENTS.md
  skills         ~/.claude/skills + enabled plugins     ~/.agents/skills (Codex reads it natively)
  commands       ~/.claude/commands/*.md                ~/.codex/prompts/*.md
  subagents      ~/.claude/agents/*.md                  ~/.codex/agents/*.toml
  hooks          ~/.claude/settings.json "hooks"        ~/.codex/hooks.json
  MCP            ~/.claude.json + <repo>/.mcp.json      ~/.codex/config.toml [mcp_servers]
  permissions    settings.json "permissions"            (rules stay Codex-only)

Targets (each optional): codex, gemini, opencode, qwen, goose, claude. Every target's hooks call
bridge/adapter.py --dispatch, which reads the hook list LIVE from the source - add a guard once, it runs everywhere.

  python3 sync.py [--dry-run] [--only base,codex,gemini,...]
Idempotent. Generated files carry an "agents-bridge" marker; a file you wrote yourself gets a .pre-bridge-<ts>.bak
copy before the first overwrite. Codex config.toml is merged inside a marked block - Codex's own writes (model,
project trust, hook trust) are preserved.
"""
