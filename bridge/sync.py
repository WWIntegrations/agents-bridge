def hooks_block(harness: str, events: dict[str, str], tool_matcher: str = ".*", timeout_ms: bool = False) -> dict:
    """{agent event name: adapter event} -> Claude-shaped hook groups calling the dispatcher."""
    mul = 1000 if timeout_ms else 1
    out = {}
    for agent_ev, our_ev in events.items():
        extra = " --with-context" if our_ev == "SessionStart" else ""
        h = {"type": "command", "command": f"{ADAPTER} --harness {harness} --dispatch --event {agent_ev}{extra}",
             "timeout": (120 if our_ev == "PreToolUse" else 60) * mul}
        grp = {"hooks": [h]}
        if our_ev in ("PreToolUse", "PostToolUse"):
            grp["matcher"] = tool_matcher
        out[agent_ev] = [grp]
    return out


