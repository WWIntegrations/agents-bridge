def src_agents() -> list[tuple[str, str, str, str]]:
    """-> [(name, description, tools, instructions)]"""
    out = []
    if CFG["source"] == "codex":
        for f in sorted((CX / "agents").glob("*.toml")):
            try:
                d = tomllib.loads(f.read_text())
            except tomllib.TOMLDecodeError:
                continue
            out.append((slug(d.get("name", f.stem)), d.get("description", ""), "", d.get("developer_instructions", "")))
        return out
    files = {f.name: f for f in sorted((CL / "agents").glob("*.md"))}
