def codex_mcp(servers: dict[str, dict], ask: dict[str, list[str]]) -> dict:
    out = {}
    for n, s in servers.items():
        if s["kind"] == "http":
            c = {"url": s["url"]}
            if s["helper"]:
                c["http_headers_helper"] = f"{X(CFG['mcp_header_helper'])} {n}"
        else:
            c = {"command": s["command"], "args": s["args"], "startup_timeout_sec": 60}
            if s["env"]:
                c["env"] = s["env"]
            same = [v for k, v in s["env_vars"] if k == v]
            diff = {k: v for k, v in s["env_vars"] if k != v}
            if diff:  # server expects another name than the host env var
                c["command"] = "/usr/bin/env"
                c["args"] = ["sh", "-c", " ".join(f'{k}="${v}"' for k, v in diff.items()) + ' exec "$0" "$@"',
                             s["command"], *s["args"]]
            if same or diff:
                c["env_vars"] = sorted(set(same + list(diff.values())))
        if n in ask:
            c["tools"] = {t: {"approval_mode": "prompt"} for t in ask[n]}
        out[n] = c
    return out


def t_codex() -> None:
    if CFG["source"] != "codex":
        link(X(CFG["agents_md"]), CX / "AGENTS.md")
    cc = CFG["codex"]
    deny, ask = src_permissions()
    gen = {k: cc[k] for k in ("model_reasoning_effort", "approval_policy", "approvals_reviewer", "sandbox_mode",
                               "web_search") if cc.get(k)}
    gen.update({"project_doc_max_bytes": 65536, "project_doc_fallback_filenames": ["CLAUDE.md"],
                "sandbox_workspace_write": {"network_access": bool(cc.get("network_access")),
                                            "writable_roots": [str(X(p)) for p in CFG["writable_roots"]]},
                "features": {"hooks": True, "multi_agent": True},
                "skills": {"max_context_tokens": 10000},
                "projects": {str(r): {"trust_level": "trusted"} for r in repos()}})
    if CFG["source"] != "codex":
        gen["mcp_servers"] = codex_mcp(src_mcp(), ask)
    write(CX / "config.toml", merge_managed_toml(CX / "config.toml", gen))
    if CFG["source"] == "codex":
        return  # Codex is the source: its own hooks/prompts/agents stay authoritative
    write(CX / "hooks.json", json.dumps({"description": "agents-bridge: every event -> adapter -> hooks from "
                                         + str(hooks_source()), "hooks": hooks_block("codex", CLAUDE_EVENTS)},
                                        indent=2) + "\n")
    # SessionStart: Codex caps injected context; raise it for memory indexes
    rules = ["# agents-bridge: generated from source permissions - do not edit", ""]
    for pre in deny:
        rules.append(f'prefix_rule(pattern={json.dumps(pre)}, decision="forbidden", justification="denied in source config")')
    write(CX / "rules" / "agents-bridge.rules", "\n".join(rules) + "\n")
    for f in src_commands():
        link(f.resolve(), CX / "prompts" / f.name)
    for name, desc, tools, body in src_agents():
        ro = bool(tools) and not re.search(r"\b(Edit|Write|MultiEdit|Bash|\*)\b", tools)
        instr = (f"Ported from a Claude Code subagent. Original tools: {tools or 'all'}.\n"
                 + ("READ-ONLY: do not edit files or run state-changing commands.\n" if ro else "") + "\n" + body)
        write(CX / "agents" / f"{name}.toml", "# agents-bridge: generated\n" +
              toml_dump({"name": name, "description": (desc or name)[:1000], "developer_instructions": instr}) + "\n")
    for r in repos():
        pm = project_mcp(r)
        if pm:
            write(r / ".codex" / "config.toml", MARK_BEG + "\n" + toml_dump({"mcp_servers": codex_mcp(pm, {})}) + "\n" + MARK_END + "\n")
            git_exclude(r, [".codex/"])


def gemini_mcp(servers: dict[str, dict]) -> dict:
    out = {}
    for n, s in servers.items():
        if s["kind"] == "http":
            c = {"httpUrl": s["url"]}
            hdr = CFG["mcp_secret_headers"].get(n)
            if hdr:
                c["headers"] = {h: v.replace("${", "$").replace("}", "") if "$" in v else f"${v}" for h, v in hdr.items()}
        else:
            env = dict(s["env"])
            env.update({k: f"${v}" for k, v in s["env_vars"]})
            c = {"command": s["command"], "args": s["args"], "timeout": 60000, **({"env": env} if env else {})}
        out[n] = c
    return out


